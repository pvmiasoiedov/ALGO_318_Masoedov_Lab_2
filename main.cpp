    cout << "=== Завдання 2. Boolean14 ===" << endl;
    
    int A, B, C; // Оголошуємо три цілих числа
    cout << "Введіть три цілих числа (A, B, C через пробіл): ";
    cin >> A >> B >> C; // Зчитуємо числа

    // Перевіряємо умову: «Рівне одне з чисел А, В, С є додатним» (> 0).
    // Перетворюємо логічні перевірки у числа (true = 1, false = 0) та додаємо їх.
    // Якщо їхня сума дорівнює рівно 1, значить, умова виконується (true).
    bool is_one_positive = ((A > 0) + (B > 0) + (C > 0) == 1);

    // Виводимо результат (boolalpha виведе "true" або "false" замість 1 або 0)
