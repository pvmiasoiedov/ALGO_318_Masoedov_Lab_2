    cout << "Введіть кількість секунд (N): ";
    cin >> sekundy; // Зчитуємо число з клавіатури

    // В одній годині 3600 секунд (60 хвилин * 60 секунд)
    // Цілочисельне ділення / відкидає залишок і дає кількість повних годин
    int godyny = sekundy / 3600; 
    cout << "Кількість повних годин: " << godyny << endl << endl;


    
