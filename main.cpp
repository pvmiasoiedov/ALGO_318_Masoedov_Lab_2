    // ЗАВДАННЯ 3: Математичний вираз (Варіант 12)
    
    cout << "=== Завдання 3. Math.12 ===" << endl;
    
    double x, num, denom, y; // Оголошуємо змінні дійсного типу (double)

    cout << "Введіть дійсний аргумент x: ";
    cin >> x; // Зчитуємо значення x

    // 1. Обчислюємо чисельник виразу:
    // log10(x) — це десятковий логарифм (lg x)
    // sin(x) — синус x
    // sqrt(...) — квадратний корінь, fabs(...) — модуль дійсного числа
    num = 2 * log10(x) * sin(x) + 0.25 * sqrt(fabs(1 - pow(sin(x), 2) * log10(x)));

    // 2. Обчислюємо знаменник виразу:
    // cbrt(...) — кубічний корінь (корінь 3-го ступеня) із виразу в дужках
